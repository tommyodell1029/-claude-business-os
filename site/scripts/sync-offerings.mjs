// Copies ../config/offerings.yaml (single source of truth for prices) into content/offerings.yaml so the site
// builds from site/ alone (Vercel uploads only this folder). Runs before every build. Commit the copy.
// Also mirrors ../config/models.yaml into lib/jarvis/models.generated.ts (model IDs + allowed roles for Jarvis).
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../config/offerings.yaml");
const dst = resolve(here, "../content/offerings.yaml");

if (existsSync(src)) {
  mkdirSync(dirname(dst), { recursive: true });
  copyFileSync(src, dst);
  console.log("offerings: synced from config/offerings.yaml");
} else if (existsSync(dst)) {
  console.log("offerings: ../config not present, using committed content/offerings.yaml");
} else {
  console.error("offerings: no config/offerings.yaml and no content/offerings.yaml");
  process.exit(1);
}

const modelsSrc = resolve(here, "../../config/models.yaml");
const modelsDst = resolve(here, "../lib/jarvis/models.generated.ts");
if (existsSync(modelsSrc)) {
  const cfg = parse(readFileSync(modelsSrc, "utf8"));
  const out = `// GENERATED by scripts/sync-offerings.mjs from config/models.yaml. Do not edit; edit config/models.yaml.\n` +
    `export const MODELS_CONFIG = ${JSON.stringify(cfg, null, 2)} as const;\n`;
  writeFileSync(modelsDst, out);
  console.log("models: synced from config/models.yaml");
} else if (existsSync(modelsDst)) {
  console.log("models: ../config not present, using committed lib/jarvis/models.generated.ts");
} else {
  console.error("models: no config/models.yaml and no lib/jarvis/models.generated.ts");
  process.exit(1);
}
